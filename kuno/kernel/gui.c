static void text(struct gpu *g, int x, int y, const char *s, u32 col, int max) {
    for (; *s && max--; s++, x += 8) {
        int c = *s; if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 32 || c > 90) c = '?';
        for (int r = 0; r < 8; r++)
            for (int b = 0; b < 8; b++)
                if (font[c - 32][r] >> b & 1) g->fill(g, x + b, y + r, 1, 1, col);
    }
}

struct win { int x, y, w, h; const char *title; u32 accent; };
static void draw_win(struct gpu *g, struct win *w) {
    g->fill(g, w->x + 4, w->y + 4, w->w, w->h, 0x00101018);               /* sombra */
    g->fill(g, w->x, w->y, w->w, w->h, 0x00202830);
    g->fill(g, w->x, w->y, w->w, 20, w->accent);
    text(g, w->x + 8, w->y + 6, w->title, 0x00FFFFFF, 60);
    g->fill(g, w->x + w->w - 16, w->y + 5, 10, 10, 0x00E04040);           /* boton cerrar */
}

void gui_render(struct gpu *g) {
    for (u32 y = 0; y < g->h; y += 4) {                                    /* fondo degradado */
        u32 t = y * 255 / g->h;
        g->fill(g, 0, y, g->w, 4, (0x10 + t / 6) << 16 | (0x20 + t / 4) << 8 | (0x50 + t / 2));
    }
    char buf[96];
    ksnprintf(buf, sizeof buf, "KUNO - GPU%d (%s) %ux%u", g->id, g->name, g->w, g->h);
    struct win term = { 40, 40, (int)g->w - 80 > 640 ? 640 : (int)g->w - 80, 300, buf, 0x00305090 };
    draw_win(g, &term);
    int lines = (term.h - 28) / 10;
    for (int i = 0; i < lines && i < KLOG_LINES; i++)
        text(g, term.x + 8, term.y + 28 + i * 10, klog_line(KLOG_LINES - lines + i), 0x0060FF80, (term.w - 16) / 8);
    struct win about = { (int)g->w - 300, (int)g->h - 200, 260, 120, "ACERCA DE", 0x00905030 };
    draw_win(g, &about);
    text(g, about.x + 12, about.y + 32, "KUNO KERNEL 0.1", 0x00FFFFFF, 30);
    text(g, about.x + 12, about.y + 48, "UNIX-STYLE X86_64", 0x00C0C0C0, 30);
    g->fill(g, 0, g->h - 28, g->w, 28, 0x00181820);                        /* barra de tareas */
    g->fill(g, 6, g->h - 24, 70, 20, 0x00305090);
    text(g, 14, g->h - 18, "KUNO", 0x00FFFFFF, 8);
}
